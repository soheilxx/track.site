export function integrationBySlug(slug: string): IntegrationCatalogEntry | undefined {
  return INTEGRATIONS.find((i) => i.slug === slug);
}

/** Delivery modes of an entry in catalogue order. */
export function integrationModes(entry: Pick<IntegrationCatalogEntry, "browser" | "server" | "offline">): IntegrationMode[] {
  return INTEGRATION_MODES.filter((m) => entry[m]);
}

/** Catalogue text language for a locale (English for locales without catalogue copy). */
export function catalogLang(locale: string): keyof LocalizedText {
  return locale === "de" ? "de" : "en";
}
