/**
 * Marketing + dashboard catalogue of integrations. Every entry is either a real connector in
 * packages/connectors (kind `destination`) or a verified shop integration from docs/10 (kind
 * `source`) — no "coming soon".
 *
 * The technical facts (delivery modes, dedup field, click ids, public ids, credential kinds, consent
 * purpose, API version, verification) mirror the connector metadata, `@track-site/policy` and
 * `packages/connectors/src/versions.ts`. `components/marketing/integrations/catalog.test.ts`
 * cross-checks every destination against the connector registry so the marketing pages can never
 * claim support the code does not have. Access notes describe vendor-side prerequisites.
 */
export type IntegrationCategory = "ads" | "analytics" | "commerce" | "affiliate" | "custom";
export type IntegrationMode = "browser" | "server" | "offline";
/** `destination` = Track delivers events to it; `source` = it delivers verified orders to Track. */
export type IntegrationKind = "destination" | "source";
/** How the implementation was checked: primary vendor documentation, secondary references (vendor docs behind a login), or recorded webhook payloads (shop platforms). */
export type IntegrationVerification = "vendor_docs" | "secondary_sources" | "recorded_payloads";
/** Vendor-side prerequisite before the server path delivers. */
export type IntegrationAccess = "open" | "vendor_setup" | "vendor_approval" | "vendor_beta";
export type ConsentPurposeId = "necessary" | "analytics" | "marketing";
export type CredentialKindId = "access_token" | "api_secret" | "oauth_refresh_token" | "oauth_access_token" | "oauth_token_secret" | "client_id" | "client_secret" | "webhook_secret" | "signing_secret";

export const INTEGRATION_CATEGORIES: readonly IntegrationCategory[] = ["ads", "analytics", "commerce", "affiliate", "custom"];
export const INTEGRATION_MODES: readonly IntegrationMode[] = ["browser", "server", "offline"];

export interface LocalizedText {
  en: string;
  de: string;
}

export interface IntegrationPublicId {
  /** Config key as the connector expects it (shown in monospace). */
  key: string;
  label: LocalizedText;
  optional?: boolean;
}

export interface IntegrationCredential {
  kind: CredentialKindId;
  /** OAuth provider id when the credential is obtained by connecting an account. */
  oauth: string | null;
  /** The destination delivers without it (network feature that is off by default). */
  optional?: boolean;
}

export interface IntegrationCatalogEntry {
  slug: string;
  /** Connector type in packages/connectors (destinations) or the shop platform id (sources). */
  type: string;
  name: string;
  /** Short label for chips, tiles and diagrams. */
  shortName: string;
  /** 1–2 characters for the original monogram glyph (no third-party logos in the repo). */
  monogram: string;
  kind: IntegrationKind;
  category: IntegrationCategory;
  /** Editorial tier used for the default ordering inside a category (1 = core platforms). */
  group: 1 | 2 | 3 | "commerce";
  browser: boolean;
  server: boolean;
  offline: boolean;
  auth: "token" | "oauth" | "api_secret" | "signing_secret" | "postback";
  /** Human-readable deduplication rule. */
  dedup: string;
  /** Vendor field that carries the shared event id (connector `dedupField`); `order_id` pairing key for sources. */
  dedupField: string | null;
  /** Click ids the policy engine allows for this destination (`DESTINATION_CLICK_IDS`). */
  clickIds: string[];
  publicIds: IntegrationPublicId[];
  credentials: IntegrationCredential[];
  /** Consent purpose the policy engine requires by default (`DESTINATION_PURPOSE`). */
  consentPurpose: ConsentPurposeId;
  /** The connector forwards hashed identifiers (SHA-256 e-mail/phone/external id) for matching. */
  hashedMatching: boolean;
  /** Pinned API version (`versions.ts`); null for sources. */
  apiVersion: string | null;
  /** Public vendor documentation the implementation was verified against; null when the docs are Track's own. */
  docsUrl: string | null;
  verification: IntegrationVerification;
  /** ISO date of the verification; null when only recorded payloads exist. */
  verifiedAt: string | null;
  access: IntegrationAccess;
  /** Network presets of a multi-network connector (affiliate). */
  presets?: string[];
  /** Search aliases (product names, click id names, common abbreviations). */
  keywords: string[];
  /** Knowledge article tags that mark an article as related (in addition to `platforms`/`shopSystems` = slug). */
  knowledgeTags: string[];
  accessNote: LocalizedText | null;
  summary: LocalizedText;
}

